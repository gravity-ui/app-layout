import {writeFile} from 'node:fs/promises';

import {build} from 'esbuild';

const result = await build({
    stdin: {
        contents:
            "export {installAssetLoader} from './src/plugins/layout/asset-loading/runtime.ts';",
        resolveDir: process.cwd(),
    },
    bundle: true,
    minify: true,
    format: 'iife',
    globalName: 'appLayoutAssetLoader',
    target: 'es2017',
    write: false,
});
const source = `(function(config){${result.outputFiles[0].text}\nappLayoutAssetLoader.installAssetLoader(config);})`;
await writeFile(
    'src/plugins/layout/asset-loading/runtime-source.ts',
    `// Generated by scripts/build-runtime.mjs. Do not edit.\nexport const runtimeSource: string = ${JSON.stringify(source)};\n`,
);
